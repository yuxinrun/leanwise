function build(rows: readonly (readonly string[])[], phase: 1 | 2 | 3 | 4, start: number): DayPlan[] {
  return rows.map((r, i) => ({
    day: start + i,
    phase,
    task: r[0], diet: r[1], activity: r[2], record: r[3], difficulty: r[4], solution: r[5],
  }));
}

